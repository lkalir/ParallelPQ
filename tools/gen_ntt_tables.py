#!/usr/bin/env python3
"""Write core/include/ppq/ntt_tables.h: the NTT twiddle factors for ML-DSA.

zetas[k] = 2^32 * zeta^bitrev8(k) mod q, centred in (-q/2, q/2], with zeta = 1753 the
primitive 512th root of unity mod q = 8380417 that FIPS 204 uses (Appendix B). They are in
Montgomery form so a Montgomery multiplication by zetas[k] multiplies by zeta^bitrev8(k).

usage: tools/gen_ntt_tables.py [OUTPUT]
"""

import sys
from pathlib import Path

Q = 8380417
ZETA = 1753
MONT = pow(2, 32, Q)


def bitrev8(k):
    return int(f"{k:08b}"[::-1], 2)


def centred(a):
    a %= Q
    return a - Q if a > Q // 2 else a


def main():
    here = Path(__file__).resolve().parent
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent / "core/include/ppq/ntt_tables.h"

    assert pow(ZETA, 256, Q) == Q - 1, "zeta must have order 512"
    zetas = [centred(MONT * pow(ZETA, bitrev8(k), Q)) for k in range(256)]

    rows = []
    for i in range(0, 256, 8):
        rows.append("    " + ", ".join(f"{z:8d}" for z in zetas[i : i + 8]) + ",")
    values = " \\\n".join(rows)

    out.write_text(
        f"""#ifndef PPQ_NTT_TABLES_H_
#define PPQ_NTT_TABLES_H_

// Generated by tools/gen_ntt_tables.py; do not edit.
//
// zetas[k] = 2^32 * 1753^bitrev8(k) mod q, centred, for k = 0..255. Entry 0 is never used by
// the transforms. The values are listed once and expand into a host table and, in GPU
// builds, a __constant__ copy for device code.

#include <cstdint>

// clang-format off
#define PPQ_ZETA_VALUES \\
{values}
// clang-format on

namespace ppq::detail {{

inline constexpr std::int32_t ZETAS[256] = {{PPQ_ZETA_VALUES}};

#if defined(__HIPCC__) || defined(__CUDACC__)
static __constant__ std::int32_t ZETAS_DEVICE[256] = {{PPQ_ZETA_VALUES}};
#endif

}} // namespace ppq::detail

#endif
"""
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
