#!/usr/bin/env python3
"""Writes the known-answer vector files under tests/vectors using hashlib."""

import argparse
import hashlib
import random
from pathlib import Path

SEED = 0x6D6C6473
RATES = {"shake128": 168, "shake256": 136}
SHAKE = {"shake128": hashlib.shake_128, "shake256": hashlib.shake_256}
EXPAND_A_BYTES = 5 * 168
SEED_BYTES = 32
T1_PACKED_BYTES = 320
MLDSA_SIGS_PER_SET = 4
MLDSA_PARAMS = {44: (4, 4), 65: (6, 5), 87: (8, 7)}
MLDSA_MSG_BYTES = {44: 64, 65: 0, 87: 200}
DIGEST_BYTES = 32


def hexstr(b):
    return b.hex() if b else "-"


def shake_vectors(rng):
    for alg, rate in RATES.items():
        in_lens = [0, 1, rate - 2, rate - 1, rate, rate + 1, 2 * rate, 2 * rate + 1, 1000]
        out_lens = [1, 32, 64, rate - 1, rate, rate + 1, EXPAND_A_BYTES]
        cases = [(n, out) for n in in_lens for out in (32, 64)]
        cases += [(3, out) for out in out_lens]
        cases += [(rate - 1, EXPAND_A_BYTES), (2 * rate + 1, EXPAND_A_BYTES)]
        for in_len, out_len in cases:
            msg = rng.randbytes(in_len)
            yield alg, msg, out_len, SHAKE[alg](msg).digest(out_len)


def write_shake(path, rng):
    with open(path, "w") as f:
        f.write("# generated by tools/kat.py from hashlib; do not edit\n")
        f.write("# algorithm input_hex out_len output_hex\n")
        for alg, msg, out_len, out in shake_vectors(rng):
            f.write(f"{alg} {hexstr(msg)} {out_len} {out.hex()}\n")


def mldsa_vectors(rng):
    """FIPS 204 tr = H(pk), mu = H(tr || 0 || 0 || M), A[i][j] stream = G(rho || j || i)."""
    for pid, (k, l) in MLDSA_PARAMS.items():
        for _ in range(MLDSA_SIGS_PER_SET):
            pk = rng.randbytes(SEED_BYTES + T1_PACKED_BYTES * k)
            msg = rng.randbytes(MLDSA_MSG_BYTES[pid])
            tr = hashlib.shake_256(pk).digest(64)
            mu = hashlib.shake_256(tr + b"\x00\x00" + msg).digest(64)
            rho = pk[:SEED_BYTES]
            digests = b"".join(
                hashlib.shake_256(
                    hashlib.shake_128(rho + bytes([j, i])).digest(EXPAND_A_BYTES)
                ).digest(DIGEST_BYTES)
                for i in range(k)
                for j in range(l)
            )
            yield pid, pk, msg, tr, mu, digests


def write_mldsa(path, rng):
    with open(path, "w") as f:
        f.write("# generated by tools/kat.py from hashlib; do not edit\n")
        f.write("# params pk_hex msg_hex tr_hex mu_hex shake256_32(A[i][j] stream) for i, j\n")
        for pid, pk, msg, tr, mu, digests in mldsa_vectors(rng):
            f.write(f"{pid} {pk.hex()} {hexstr(msg)} {tr.hex()} {mu.hex()} {digests.hex()}\n")


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, default=here.parent / "tests" / "vectors")
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_shake(args.out_dir / "shake.txt", random.Random(SEED))
    write_mldsa(args.out_dir / "mldsa_hash.txt", random.Random(SEED + 1))


if __name__ == "__main__":
    main()
